import sqlite3
import json
from pathlib import Path

DB_PATH = Path(__file__).with_name("health_medicine.db")

def init_database():
    con = sqlite3.connect(DB_PATH)
    cur = con.cursor()

    # Drop existing tables
    cur.execute("DROP TABLE IF EXISTS condition_medicines")
    cur.execute("DROP TABLE IF EXISTS conditions")
    cur.execute("DROP TABLE IF EXISTS medicines")

    # Create tables
    cur.execute("""
        CREATE TABLE medicines (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            medicine_id INTEGER UNIQUE,
            name TEXT NOT NULL,
            active_ingredient TEXT,
            category TEXT,
            uses TEXT,
            form TEXT,
            example_strength TEXT,
            precautions TEXT,
            common_side_effects TEXT
        )
    """)

    cur.execute("""
        CREATE TABLE conditions (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            condition_id INTEGER UNIQUE,
            name TEXT NOT NULL,
            symptoms TEXT,
            diet TEXT,
            fitness TEXT
        )
    """)

    cur.execute("""
        CREATE TABLE condition_medicines (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            condition_id INTEGER,
            medicine_id INTEGER,
            FOREIGN KEY (condition_id) REFERENCES conditions (condition_id),
            FOREIGN KEY (medicine_id) REFERENCES medicines (medicine_id)
        )
    """)

    # Insert medicines
    med_name_to_id = {}
    for m in MEDICINES_DATA:
        cur.execute("""
            INSERT INTO medicines (medicine_id, name, active_ingredient, category, uses, form, example_strength, precautions, common_side_effects)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
        """, (
            m["medicine_id"], m["name"], m["active_ingredient"], m["category"],
            m["uses"], m["form"], m["example_strength"], m["precautions"], m["common_side_effects"]
        ))
        med_name_to_id[m["name"].lower()] = m["medicine_id"]

    # Insert conditions and condition_medicines links
    for c in CONDITIONS_DATA:
        cur.execute("""
            INSERT INTO conditions (condition_id, name, symptoms, diet, fitness)
            VALUES (?, ?, ?, ?, ?)
        """, (
            c["condition_id"], c["condition"], json.dumps(c.get("symptoms", [])), c.get("diet", ""), c.get("fitness", "")
        ))

        # Insert relations
        for m_name in c.get("medicine_names", []):
            m_id = med_name_to_id.get(m_name.lower())
            if m_id:
                cur.execute("""
                    INSERT INTO condition_medicines (condition_id, medicine_id)
                    VALUES (?, ?)
                """, (c["condition_id"], m_id))

    con.commit()
    con.close()
    print(f"Database initialized successfully at {DB_PATH}")

if __name__ == "__main__":
    init_database()
